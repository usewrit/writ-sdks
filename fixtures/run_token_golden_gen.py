"""Generate ``run_token_golden.json``: the run token golden vectors (CONTRACT.md §11 "Token mode").

Standard library only. Run it from anywhere and redirect its output::

    python3 sdks/fixtures/run_token_golden_gen.py > sdks/fixtures/run_token_golden.json

A run token is a JWT, HS256, signed with the publication's secret key (``wsk_...``):

- the HMAC key is the secret key's UTF-8 bytes, the ``wsk_`` prefix included;
- header: ``{"alg":"HS256","typ":"JWT"}``, exactly these two keys in this order;
- payload: ``{"pub":...,"iat":...,"exp":...,"sub":...}``, exactly this key order, ``sub`` left out
  when there is none; ``exp = iat + ttl_seconds``;
- both are compact JSON (no whitespace), non-ASCII emitted as is, encoded as UTF-8;
- each part is base64url without padding; the token is ``header.payload.signature``, the
  signature being HMAC-SHA256 over the ASCII bytes of ``header.payload``.

``@usewrit/server`` (``mintRunToken``) and ``usewrit`` (``mint_run_token``) must reproduce these
bytes exactly; both test suites read the generated file.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
from typing import Any

SECRET = "wsk_0123456789abcdefghijABCDEFGHIJ0123456789"
PUBLICATION = "pub_0123456789abcdefABCDEF"
SUB = "u42"
IAT = 1791550000
TTL_SECONDS = 600


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def compact(value: dict[str, Any]) -> str:
    # Insertion order, never sorted: the order is part of the bytes.
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def vector(sub: str | None) -> dict[str, Any]:
    header_json = compact({"alg": "HS256", "typ": "JWT"})
    claims: dict[str, Any] = {"pub": PUBLICATION, "iat": IAT, "exp": IAT + TTL_SECONDS}
    if sub is not None:
        claims["sub"] = sub
    payload_json = compact(claims)
    signing_input = f"{b64url(header_json.encode('utf-8'))}.{b64url(payload_json.encode('utf-8'))}"
    signature = hmac.new(SECRET.encode("utf-8"), signing_input.encode("ascii"), hashlib.sha256).digest()
    return {
        "sub": sub,
        "exp": IAT + TTL_SECONDS,
        "header_json": header_json,
        "payload_json": payload_json,
        "signing_input": signing_input,
        "token": f"{signing_input}.{b64url(signature)}",
    }


def main() -> None:
    golden = {
        "_about": (
            "Run tokens (CONTRACT.md §11 'Token mode'): a JWT, HS256, keyed with the UTF-8 bytes of the "
            "publication's secret key (wsk_ prefix included). Header {\"alg\":\"HS256\",\"typ\":\"JWT\"} and "
            "payload {\"pub\",\"iat\",\"exp\",\"sub\"?} in exactly that key order, compact JSON, base64url "
            "without padding. Generated by run_token_golden_gen.py; @usewrit/server (mintRunToken) and "
            "usewrit (mint_run_token) must reproduce these bytes exactly."
        ),
        "secret": SECRET,
        "publication": PUBLICATION,
        "iat": IAT,
        "ttl_seconds": TTL_SECONDS,
        "with_sub": vector(SUB),
        "without_sub": vector(None),
    }
    print(json.dumps(golden, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
